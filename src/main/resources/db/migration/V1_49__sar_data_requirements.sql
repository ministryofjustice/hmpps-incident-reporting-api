-- Example values and subject access request (SAR) classification for every column (IR-2037).
--
-- These feed the SAR Data Requirements extract (scripts/generate-sar-data-requirements.sh), the document the
-- Offender SAR team review at the data review checkpoint of the SAR change control process. Incident reporting
-- is going through that process as a New Product (IR-1461), so every element needs an example value and a
-- statement of whether it reaches a prisoner's report. Comments only - no schema or data change.
--
-- Each column comment gains two tags, between the description and the existing sensitivity tag:
--
--   '... description text. [Example: SELF_HARM_1] [SAR: Y] [Sensitivity: SPECIAL-CATEGORY]'
--
-- [SAR: Y] means the value reaches the report under the response proposed for the data review (IR-1424),
-- whether it is rendered from this column or from the column it mirrors. [SAR: N] is for internal keys and
-- display order, NOMIS-only and sync fields, process flags, the legacy NOMIS wording of questions and answers
-- (the label is shown instead), and the constant_* and analytical_marker reference tables, which the service
-- never reads. The response does not exist yet in that form, so these are a proposal
-- for the Offender SAR team to confirm or change; their decision goes in a later migration rather than an edit
-- to this one.
--
-- The proposal includes other people named on a report - other prisoners and staff - and the free-text fields
-- that routinely describe them. Redacting third-party data is the Offender SAR team's job, so the default is to
-- return it and let them redact. That default is one of the questions put to them at the data review.
--
-- Example values for code columns are real codes. Every other example is invented, and the free-text examples
-- are deliberately bland: they illustrate the kind of content, not real incidents.
--
-- First, comments from V1_48 are corrected, because the extract quotes them to the Offender SAR team:
--
--   * report.type, history.type and constant_type.code gave SELF_HARM, ASSAULT and FIND_OF_ILLICIT_ITEMS as
--     examples. SELF_HARM and ASSAULT are type family codes, and FIND_OF_ILLICIT_ITEMS does not exist - the
--     type codes carry a numeric suffix (SELF_HARM_1, ASSAULT_5, FIND_6).
--   * prisoner_involvement.prisoner_role gave SUSPECTED_PERPETRATOR, which does not exist - the role is
--     SUSPECTED_ASSAILANT.
--   * report.title said it is written by the reporter. For reports created in DPS it is generated by the
--     UI from the incident type, the prisoners involved and the prison (see the commit that made it TEXT,
--     #534), so it names every prisoner on the report.
--   * The code, question/response and label columns of question, response, historical_question and
--     historical_response described question and response as the wording and label as a display copy of it.
--     It is the other way round. The question sets are configured in the front end (hmpps-incident-reporting,
--     server/reportConfiguration/types), which is the source of truth; this database only receives what was
--     asked and answered. The code is the business key that says which question was asked or which answer
--     was chosen. The label is the wording the user was shown at the time, stored so the form can be
--     reconstructed as it was presented even after its wording is corrected. question and response are the
--     legacy form NOMIS held - often capitals, misspellings, missing punctuation - left unchanged because
--     downstream systems may process on them, and expected to go once NOMIS is switched off. Some newer
--     types (KEY_OR_LOCK_3, TOOL_LOSS_2, UNLAWFUL_DETENTION_1) put a key such as lock_type there instead,
--     which is not for display. The question table comment is corrected to match.

COMMENT ON COLUMN report.title IS 'Short title for the incident. For reports created in DPS it is generated automatically from the incident type, the prison number and surname of every prisoner involved and the prison, so it names everyone on the report. Reports that came from NOMIS carry the title the reporter wrote, which in practice often names people or summarises what happened. [Sensitivity: SPECIAL-CATEGORY]';
COMMENT ON COLUMN report.type IS 'What kind of incident this is, for example SELF_HARM_1, DEATH_OTHER_1, ASSAULT_5 or FIND_6. Drives which questions are asked. This is Article 9 or Article 10 data about everyone named on the report whichever value it holds - that a report exists and is a self-harm report discloses health data about the prisoner it concerns. Values are listed in constant_type and grouped by constant_type_family. [Sensitivity: SPECIAL-CATEGORY]';
COMMENT ON COLUMN prisoner_involvement.prisoner_role IS 'How the prisoner was involved, for example VICTIM, SUSPECTED_ASSAILANT, ACTIVE_INVOLVEMENT or PRESENT_AT_SCENE. On an assault or a find of illicit items, recording someone as a suspected assailant is an allegation of offending in custody against a named person - criminal offence data under Article 10, which DPA 2018 s.11(2) extends to alleged offences. Values are in constant_prisoner_role. [Sensitivity: SPECIAL-CATEGORY]';
COMMENT ON COLUMN history.type IS 'The incident type the report held before it was changed - so a report now typed ASSAULT_5 may have a history row typed SELF_HARM_1. Carries the same sensitivity as report.type, and note that it discloses what the incident was once believed to be. Values are in constant_type. [Sensitivity: SPECIAL-CATEGORY]';
COMMENT ON COLUMN constant_type.code IS 'The type code as stored in report.type and history.type, for example SELF_HARM_1 or ASSAULT_5. [Sensitivity: NONE]';

COMMENT ON TABLE question IS 'One question asked on a report, in the order it was asked. Which questions apply is decided by report.type. The question sets - the questions, the answers offered and their wording - are configured in the incident reporting front end, which is the source of truth; this table only receives what was asked on each report, with the wording as shown at the time, so a later correction to the question set does not rewrite existing reports. Answers hang off this in response - a question with no response rows was asked but not answered.';

COMMENT ON COLUMN question.code IS 'The business key for the question: says which question in the incident type''s question set was asked. The question sets are configured in the incident reporting front end. Wording is corrected over time but the code does not change, so it is the key for analysing answers across reports. [Sensitivity: NONE]';
COMMENT ON COLUMN question.question IS 'The question in the legacy form NOMIS held. For questions that came from NOMIS this is often in capitals, with spelling mistakes and missing punctuation, and is kept unchanged because systems downstream may process on it. Some newer incident types hold a key such as lock_type here rather than a sentence. Not for display - label is the wording the user saw. Expected to be removed once NOMIS is switched off. Form wording rather than an answer, so not personal data in itself. [Sensitivity: NONE]';
COMMENT ON COLUMN question.label IS 'The question exactly as it was shown to the user completing the report, at the time they answered it. Wording is corrected from time to time - spelling, punctuation - so it is stored with each report, so the form can be reconstructed as it was presented. This is the wording to display. Form wording rather than an answer, so not personal data in itself. [Sensitivity: NONE]';

COMMENT ON COLUMN response.code IS 'The business key for the answer: says which of the answers offered to the question was chosen. The answers offered are configured in the incident reporting front end with the questions. Wording is corrected over time but the code does not change, so it is the key for analysing answers across reports, and the key analytical_marker uses to flag answers that indicate serious harm. Discloses what was answered, so it is as sensitive as the wording. [Sensitivity: SPECIAL-CATEGORY]';
COMMENT ON COLUMN response.response IS 'The answer in the legacy form NOMIS held. For answers that came from NOMIS this is often in capitals, with spelling mistakes and missing punctuation, and is kept unchanged because systems downstream may process on it. Some newer incident types hold a key such as who_identified_the_error_court here rather than words. Not for display - label is the wording the user saw. Expected to be removed once NOMIS is switched off. Still records what happened in the incident - injuries, weapons, methods, whether the police attended - about the people named on the report. [Sensitivity: SPECIAL-CATEGORY]';
COMMENT ON COLUMN response.label IS 'The answer exactly as it was shown to the user completing the report, at the time they chose it. Wording is corrected from time to time - spelling, punctuation - so it is stored with each report, so the form can be reconstructed as it was presented. This is the wording to display. Records what happened in the incident about the people named on the report. [Sensitivity: SPECIAL-CATEGORY]';

COMMENT ON COLUMN historical_question.code IS 'The business key for the question in the question set that applied before the report''s type was changed. As question.code: says which question was asked, and does not change when the wording is corrected. [Sensitivity: NONE]';
COMMENT ON COLUMN historical_question.question IS 'The question in the legacy form NOMIS held, as it stood before the report''s type was changed. As question.question: often in capitals or misspelt, or a key such as lock_type for some newer incident types. Not for display - label is the wording the user saw. Expected to be removed once NOMIS is switched off. Form wording rather than an answer. [Sensitivity: NONE]';
COMMENT ON COLUMN historical_question.label IS 'The question exactly as it was shown to the user, before the report''s type was changed. As question.label: the wording to display, stored so the form can be reconstructed as it was presented. Form wording rather than an answer. [Sensitivity: NONE]';

COMMENT ON COLUMN historical_response.code IS 'The business key for the answer chosen, in the question set that applied before the report''s type was changed. As response.code: does not change when the wording is corrected. Discloses what was answered. [Sensitivity: SPECIAL-CATEGORY]';
COMMENT ON COLUMN historical_response.response IS 'The answer in the legacy form NOMIS held, as it stood before the report''s type was changed. As response.response: often in capitals or misspelt, or a key for some newer incident types. Not for display - label is the wording the user saw. Expected to be removed once NOMIS is switched off. Still records what happened in the incident about the people named on the report. [Sensitivity: SPECIAL-CATEGORY]';
COMMENT ON COLUMN historical_response.label IS 'The answer exactly as it was shown to the user, before the report''s type was changed. As response.label: the wording to display, stored so the form can be reconstructed as it was presented. Records what happened in the incident about the people named on the report. [Sensitivity: SPECIAL-CATEGORY]';

